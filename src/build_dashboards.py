"""Build the dashboard data files in site/data/ from the pipeline's analytical outputs.

Run after src/ingest.py has written data/analytical_outputs:

    python3 src/build_dashboards.py

The dashboards (site/*.html) load these files with plain <script> tags, so they keep working
when opened straight from disk and when published to GitHub Pages.
"""
import argparse
import json
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]

STRATEGIC_SQL = """
SELECT strftime(signup_month, '%Y-%m') AS month, channel, age_days AS age, model_version AS model,
       cohort_status AS status, registrations AS n, mature_customers AS mature,
       paid_attributed_customers AS paid, contribution_cents AS real,
       expected_comparable_cents AS expected, revenue_cents AS revenue,
       eligible_spend_cents AS spend, cac_usd::DOUBLE AS cac,
       revenue_roas::DOUBLE AS roas, realized_per_spend::DOUBLE AS eff
FROM read_parquet(?)
WHERE run_id = ? AND allocation_method = 'CALENDAR'
ORDER BY month, channel, age, model
"""

OPERATIONAL_SQL = """
SELECT strftime(report_date, '%Y-%m-%d') AS day, campaign_id AS campaign, actual_cents AS actual,
       eligible_spend_cents AS eligible, planned_cents AS plan, actual_to_date_cents AS atd,
       plan_to_date_cents AS ptd, registrations AS n, cac_usd::DOUBLE AS cac,
       mature_30_customers AS m, activated_30_customers AS a, baseline_forecast_total_cents AS forecast
FROM read_parquet(?)
WHERE run_id = ?
ORDER BY campaign, day
"""


def query(con, sql, *params):
    cursor = con.execute(sql, list(params))
    columns = [d[0] for d in cursor.description]
    return [dict(zip(columns, row)) for row in cursor.fetchall()]


def write(path, snapshot, rows):
    path.write_text(
        "// Generated by src/build_dashboards.py from data/analytical_outputs. Do not edit by hand.\n"
        f"const snapshot={json.dumps(snapshot)};\n"
        f"const data={json.dumps(rows, separators=(',', ':'))};\n",
        encoding="utf-8",
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--outputs", type=Path, default=ROOT / "data/analytical_outputs")
    parser.add_argument("--site", type=Path, default=ROOT / "site")
    args = parser.parse_args()

    manifest = json.loads((args.outputs / "pipeline_manifest.json").read_text(encoding="utf-8"))
    run = manifest["run_id"]
    snapshot = {"run": run, "build": manifest["build_version"], "asOf": manifest["effective_cutoff"][:10]}

    con = duckdb.connect()
    strategic = query(con, STRATEGIC_SQL, str(args.outputs / "channel_cohort.parquet"), run)
    operational = query(con, OPERATIONAL_SQL, str(args.outputs / "campaign_performance_day.parquet"), run)

    # The dashboards assume these invariants; fail the build rather than publish misleading charts.
    assert strategic and operational, f"no rows for run {run}"
    assert all(r["mature"] <= r["n"] and r["paid"] <= r["n"] for r in strategic)
    spend = {}
    for r in strategic:  # payback compares one cohort spend against value at every age
        spend.setdefault((r["month"], r["channel"]), set()).add(r["spend"])
    assert all(len(s) == 1 for s in spend.values()), "cohort spend must not vary by age or model"
    assert all(r["a"] <= r["m"] <= r["n"] for r in operational)
    days = {}
    for r in operational:
        days.setdefault(r["campaign"], []).append(r["day"])
    assert len({tuple(d) for d in days.values()}) == 1, "campaigns must share the same daily calendar"

    (args.site / "data").mkdir(parents=True, exist_ok=True)
    write(args.site / "data/strategic.js", snapshot, strategic)
    write(args.site / "data/operational.js", snapshot, operational)
    print(f"{run} as of {snapshot['asOf']}: {len(strategic)} cohort rows, {len(operational)} campaign-day rows")


if __name__ == "__main__":
    main()
